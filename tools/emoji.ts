// Writes the emoji assets in android/assets from Unicode's emoji-test.txt and CLDR's English annotations.
// - emoji.txt: one line per group, emoji split by spaces.
// - emoji-words.txt: each emoji, its name and the words that find it in a search.
// - emoji-tones.txt: each emoji that takes a skin tone, and its five toned forms from light to dark.
// Usage: bun tools/emoji.ts emoji-test.txt annotations/en.xml annotationsDerived/en.xml
// Get emoji-test.txt from https://unicode.org/Public/emoji/<version>/emoji-test.txt, and the
// annotations from common/annotations and common/annotationsDerived in https://github.com/unicode-org/cldr.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [source, ...annotationFiles] = process.argv.slice(2);
if (!source || annotationFiles.length === 0) throw new Error("Pass emoji-test.txt and the CLDR annotation files");

const TONES = [0x1f3fb, 0x1f3fc, 0x1f3fd, 0x1f3fe, 0x1f3ff];
const isTone = (code: number) => TONES.includes(code);
// CLDR and toned forms often leave out the emoji presentation selector, so compare without it.
const bare = (emoji: string) => emoji.replaceAll("️", "");

const text = readFileSync(source, "utf8");
const version = text.match(/^# Version: (\S+)/m)?.[1] ?? "unknown";
const groups = new Map<string, string[]>();
const names = new Map<string, string>();
const toned: { codes: number[]; emoji: string }[] = [];
let group = "";
for (const line of text.split(/\r?\n/)) {
  const heading = line.match(/^# group: (.+)$/);
  if (heading) group = heading[1];
  const entry = line.match(/^([0-9A-F ]+);\s*fully-qualified\s*#\s*\S+\s+E[\d.]+\s+(.+)$/);
  if (!entry || group === "Component") continue;
  const codes = entry[1].trim().split(" ").map((code) => parseInt(code, 16));
  const emoji = String.fromCodePoint(...codes);
  // Skin tones are variants of an emoji already in the list.
  if (codes.some(isTone)) {
    toned.push({ codes, emoji });
    continue;
  }
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group)!.push(emoji);
  names.set(emoji, entry[2].trim().toLowerCase());
}
const byBare = new Map([...names.keys()].map((emoji) => [bare(emoji), emoji]));

const keywords = new Map<string, string[]>();
for (const file of annotationFiles) {
  for (const match of readFileSync(file, "utf8").matchAll(/<annotation cp="([^"]+)">([^<]+)<\/annotation>/g)) {
    const emoji = byBare.get(bare(match[1]));
    if (!emoji || keywords.has(emoji)) continue;
    const name = names.get(emoji)!;
    keywords.set(emoji, match[2].split("|").map((word) => word.trim().toLowerCase()).filter((word) => word && word !== name));
  }
}

// Only forms where each person has the same tone. Mixed tones would need a choice for each person.
const tones = new Map<string, string[]>();
for (const { codes, emoji } of toned) {
  const used = new Set(codes.filter(isTone));
  if (used.size !== 1) continue;
  const base = byBare.get(bare(String.fromCodePoint(...codes.filter((code) => !isTone(code)))));
  if (!base) continue;
  if (!tones.has(base)) tones.set(base, []);
  tones.get(base)![TONES.indexOf([...used][0])] ??= emoji;
}
for (const [base, forms] of tones) if (forms.filter(Boolean).length !== TONES.length) tones.delete(base);

const header = `# Generated by tools/emoji.ts from Unicode emoji-test.txt ${version} and CLDR annotations.`;
const write = (name: string, lines: string[]) =>
  writeFileSync(join(import.meta.dir, "../android/assets", name), [header, ...lines].join("\n") + "\n");
write("emoji.txt", [...groups].map(([name, emoji]) => `${name}\t${emoji.join(" ")}`));
write("emoji-words.txt", [...names].map(([emoji, name]) => `${emoji}\t${name}\t${(keywords.get(emoji) ?? []).join("|")}`));
write("emoji-tones.txt", [...tones].map(([base, forms]) => `${base}\t${forms.join(" ")}`));
console.log([...groups].map(([name, emoji]) => `${name}: ${emoji.length}`).join("\n"));
console.log(`Words: ${keywords.size} of ${names.size}. Skin tones: ${tones.size}.`);
